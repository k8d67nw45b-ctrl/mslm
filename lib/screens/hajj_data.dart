class HajjStep {
  final String id;
  final String title;
  final String details;
  final String dua;
  final String warning;
  const HajjStep(this.id, this.title, this.details, this.dua, this.warning);
}

class HajjKind {
  final String id;
  final String title;
  final List<HajjStep> steps;
  const HajjKind(this.id, this.title, this.steps);
}

